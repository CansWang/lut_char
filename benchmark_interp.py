def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument("--input-dir", default="output/uniform/",
                    help="Directory of .mat files (default: output/uniform/)")
    ap.add_argument("--device", default="sg13_lv_pmos",
                    help="Device name (default: sg13_lv_pmos — has 3 grids)")
    ap.add_argument("--corner", default="TT",
                    help="Process corner (default: TT)")
    ap.add_argument("--temp", type=int, default=27,
                    help="Temperature in °C (default: 27)")
    ap.add_argument("--l-index", type=int, default=0,
                    help="L index to slice (default: 0 — Lmin)")
    ap.add_argument("--n-query", type=int, default=300,
                    help="Query set size (default: 300 — small because we now "
                         "run 3 sweeps (3D + VGS + VDS) and pchip dominates. "
                         "Bump to 5000+ for tighter timing precision.)")
    ap.add_argument("--repeats", type=int, default=3,
                    help="Timing repeats (median, default: 3; bump to 5+ "
                         "for tighter median variance)")
    ap.add_argument("--seed", type=int, default=0,
                    help="Random seed for query set (default: 0)")
    ap.add_argument("--vars", nargs="+", default=None,
                    help="Variable subset (default: all 14)")
    ap.add_argument("--no-accuracy", action="store_true",
                    help="Skip accuracy comparison")
    ap.add_argument("--no-plot", action="store_true",
                    help="Skip plot generation")
    ap.add_argument("--out", default="benchmark_interp.png",
                    help="Output plot path (default: ./benchmark_interp.png)")
    ap.add_argument("--pchip-impl", choices=("scipy", "fast"), default="scipy",
                    help="Pchip implementation. 'scipy' = stock RGI; 'fast' = "
                         "monkey-patch RGI._do_pchip to skip the per-call "
                         "PchipInterpolator/BPoly construction (see fast_pchip.py). "
                         "Results are bit-exact identical; speedup is on the "
                         "pchip qps numbers only.")
    args = ap.parse_args()

    if args.pchip_impl == "fast":
        import fast_pchip
        fast_pchip.enable()

    input_dir = Path(args.input_dir)
    if not input_dir.is_dir():
        sys.exit(f"Input directory not found: {input_dir}")

    # --- Discover files ---
    files = discover_files(input_dir, args.device, args.corner, args.temp)
    if not files:
        sys.exit(f"No files matching {args.device} {args.corner} {args.temp}°C "
                 f"in {input_dir}")

    print(f"Device : {args.device}")
    print(f"Corner : {args.corner}   Temp : {args.temp}°C   L-index : {args.l_index}")
    print(f"Query  : N={args.n_query}, repeats={args.repeats}, seed={args.seed}")
    print(f"Pchip  : {args.pchip_impl}"
          + (" (fast_pchip patched — skips BPoly construction per call)"
             if args.pchip_impl == "fast" else " (stock scipy)"))
    print(f"Found  : {len(files)} grid(s):")
    for f in files:
        print(f"          {f['vgs_step']*1000:g} mV  →  {f['path'].name}")

    # --- Load full 4-D tables, validate, then slice down to 3-D ---
    print("\nLoading & validating...")
    tables = [load_mat_table(f["path"]) for f in files]
    ref_full = tables[0]
    for t in tables[1:]:
        validate_axes(ref_full, t)
    print("Axes validated (L, VSB identical; VGS/VDS bounds match).")

    slices = []
    for t in tables:
        sl = slice_3d(t, args.l_index)
        sl["meta"]["vgs_step_mv"] = t["meta"]["vgs_step"] * 1000.0
        slices.append(sl)
    ref = slices[0]
    print(f"Reference grid: {ref['meta']['vgs_step_mv']:g} mV (finest)")

    available = set(ref["data"])
    if args.vars:
        missing = [v for v in args.vars if v not in available]
        if missing:
            print(f"  [warn] requested vars not in data, skipping: {missing}")
        vars_to_run = [v for v in args.vars if v in available]
    else:
        vars_to_run = [v for v in DATA_KEYS if v in available]
    if not vars_to_run:
        sys.exit("No variables to benchmark.")

    # --- Build query sets: full 3D random + per-axis sweeps ---
    sweeps = [
        ("3D",  make_query_set(ref["axes"], args.n_query, seed=args.seed)),
        ("VGS", make_query_set_axis(ref["axes"], args.n_query, "VGS",
                                    seed=args.seed)),
        ("VDS", make_query_set_axis(ref["axes"], args.n_query, "VDS",
                                    seed=args.seed)),
    ]
    pin_vgs = float(np.clip(_AXIS_PIN["VGS"],
                            ref["axes"]["VGS"].min(), ref["axes"]["VGS"].max()))
    pin_vds = float(np.clip(_AXIS_PIN["VDS"],
                            ref["axes"]["VDS"].min(), ref["axes"]["VDS"].max()))
    pin_vsb = float(np.clip(_AXIS_PIN["VSB"],
                            ref["axes"]["VSB"].min(), ref["axes"]["VSB"].max()))
    print(f"Query  : 3D random, VGS-sweep @ (VDS={pin_vds:g},VSB={pin_vsb:g}), "
          f"VDS-sweep @ (VGS={pin_vgs:g},VSB={pin_vsb:g})")

    # --- Time & accuracy loop ---
    # Build ONE multi-output interpolator per (method, domain, slice). Each
    # query returns all variables at the same query points, so the locate +
    # cell-weight computation is amortized across all 14 variables.
    print("\nRunning benchmark...")
    rows = []
    cache_ref = {}  # (axis, var, method, domain) → y_ref vec
    for method in METHODS:
        for domain in DOMAINS:
            for sl in slices:
                grid_mv = sl["meta"]["vgs_step_mv"]
                t0 = time.perf_counter()
                interp = make_combined_interp(sl, method, domain)
                build_s = time.perf_counter() - t0
                var_names = interp.var_names
                is_ref = (sl is ref)
                for axis_name, query_pts in sweeps:
                    query_s, y_all = time_query(interp, query_pts, args.repeats)
                    qps = args.n_query / query_s if query_s > 0 else np.inf

                    for i, var in enumerate(var_names):
                        if var not in vars_to_run:
                            continue
                        y_var = y_all[:, i]

                        rms = p99 = mx = np.nan
                        rms_t = p99_t = mx_t = np.nan
                        n_kept = n_total = 0
                        key = (axis_name, var, method, domain)
                        if is_ref:
                            cache_ref[key] = y_var
                        elif not args.no_accuracy:
                            y_ref = cache_ref.get(key)
                            if y_ref is not None:
                                rms, p99, mx = relative_error(y_var, y_ref)
                                floor = ABS_FLOOR.get(var, 0.0)
                                rms_t, p99_t, mx_t, n_kept, n_total = \
                                    relative_error_true(y_var, y_ref, floor)

                        rows.append({
                            "axis":     axis_name,
                            "var":      var,
                            "grid(mV)": f"{grid_mv:g}",
                            "method":   method,
                            "domain":   domain,
                            "build_ms": f"{build_s*1000:.1f}",
                            "qps":      f"{qps:,.0f}",
                            "rms_err":  ("—" if is_ref else
                                         (f"{rms:.2e}" if np.isfinite(rms) else "—")),
                            "p99_err":  ("—" if is_ref else
                                         (f"{p99:.2e}" if np.isfinite(p99) else "—")),
                            "max_err":  ("—" if is_ref else
                                         (f"{mx:.2e}" if np.isfinite(mx) else "—")),
                            "rms_rel":  ("—" if is_ref else
                                         (f"{rms_t:.2e}" if np.isfinite(rms_t) else "—")),
                            "max_rel":  ("—" if is_ref else
                                         (f"{mx_t:.2e}" if np.isfinite(mx_t) else "—")),
                            "kept":     ("—" if is_ref else
                                         f"{n_kept}/{n_total}"),
                            "_qps":     qps,
                            "_rms_err": rms,
                            "_max_err": mx,
                            "_rms_rel": rms_t,
                            "_max_rel": mx_t,
                        })

    print("\n=== Results ===\n")
    print_table([{k: v for k, v in r.items() if not k.startswith("_")}
                 for r in rows])

    if not args.no_plot:
        base_title = (f" — {args.device} {args.corner} {args.temp}°C "
                      f"(L-idx {args.l_index})")
        out_path = Path(args.out)
        stem, ext = out_path.stem, out_path.suffix
        print()

        # Drop the reference grid from plotted rows: its "error" is just a
        # sentinel (it has no finer grid to compare against), not a real
        # measurement, so including it is misleading.
        ref_grid_label = f"{ref['meta']['vgs_step_mv']:g}"
        rows_plot = [r for r in rows if r["grid(mV)"] != ref_grid_label]
        print(f"Plotting (excluding reference grid {ref_grid_label} mV).")

        # 3D random sweep — keep both scaled and true metrics
        rows_3d = [r for r in rows_plot if r["axis"] == "3D"]
        make_plot(rows_3d, out_path.with_name(f"{stem}_rms{ext}"),
                  "_rms_err", "RMS rel. error (scaled)",
                  title_suffix=base_title + ", 3D random")
        make_plot(rows_3d, out_path.with_name(f"{stem}_max{ext}"),
                  "_max_err", "max rel. error (scaled)",
                  title_suffix=base_title + ", 3D random")
        make_plot(rows_3d, out_path.with_name(f"{stem}_rms_true{ext}"),
                  "_rms_rel", "RMS |Δy/y| (floored)",
                  title_suffix=base_title + ", 3D random")
        make_plot(rows_3d, out_path.with_name(f"{stem}_max_true{ext}"),
                  "_max_rel", "max |Δy/y| (floored)",
                  title_suffix=base_title + ", 3D random")

        # Per-axis sweeps — only the floored "true" metric (scaled is
        # misleading for the same reason it's misleading in 3D).
        for axis_name in ("VGS", "VDS"):
            rows_ax = [r for r in rows_plot if r["axis"] == axis_name]
            suffix = base_title + f", sweep {axis_name} only"
            make_plot(rows_ax,
                      out_path.with_name(f"{stem}_rms_true_{axis_name}{ext}"),
                      "_rms_rel", f"RMS |Δy/y| (floored, {axis_name} sweep)",
                      title_suffix=suffix)
            make_plot(rows_ax,
                      out_path.with_name(f"{stem}_max_true_{axis_name}{ext}"),
                      "_max_rel", f"max |Δy/y| (floored, {axis_name} sweep)",
                      title_suffix=suffix)

    print("\nDone.")


if __name__ == "__main__":
    main()
