# Phase 2 — Interpolator factory
# ---------------------------------------------------------------------------

# Log-domain transform: asinh(x / scale).
#   - Sign-preserving and round-trips exactly (no sign-flip artifact).
#   - For |x| >> scale, asinh(x/s) ≈ sign(x) * log(2|x|/s)  (true log behavior).
#   - For |x| << scale, asinh(x/s) ≈ x/s                    (linear, smooth).
#   - scale = median(|values|) so the "log knee" sits in the middle of the data,
#     giving log-like behavior for the typical many-decade vars (ID, GM, GDS).
class _AsinhWrapped:
    """Wrap an interpolator so it returns scale * sinh(base(pts))."""
    __slots__ = ("base", "scale")
    def __init__(self, base, scale):
        self.base = base
        self.scale = scale
    def __call__(self, pts):
        return self.scale * np.sinh(self.base(pts))


def make_interp(slice3d, var: str, method: str, domain: str):
    """
    Build a single-output interpolator for one variable. Retained for
    reference; the main loop uses `make_combined_interp` for speed.
    """
    axes = slice3d["axes"]
    grid = (axes["VGS"], axes["VDS"], axes["VSB"])
    values = slice3d["data"][var]
    if domain == "log":
        scale = float(np.median(np.abs(values)))
        if not np.isfinite(scale) or scale == 0:
            scale = 1.0
        transformed = np.arcsinh(values / scale)
    else:
        transformed = values
    rgi = RegularGridInterpolator(
        grid, transformed, method=method,
        bounds_error=False, fill_value=np.nan,
    )
    return _AsinhWrapped(rgi, scale) if domain == "log" else rgi


class _CombinedInterp:
    """
    Multi-output interpolator: one RegularGridInterpolator over a values array
    of shape (nVGS, nVDS, nVSB, n_vars). Each call returns shape (N, n_vars).
    For log domain, the per-variable arcsinh scales are inverted on the way
    out so the caller sees variables in their natural units.
    """
    __slots__ = ("rgi", "var_names", "scales")
    def __init__(self, rgi, var_names, scales=None):
        self.rgi = rgi
        self.var_names = var_names
        self.scales = scales  # None for linear domain, np.ndarray for log
    def __call__(self, pts):
        y = self.rgi(pts)  # (N, n_vars)
        if self.scales is None:
            return y
        return self.scales * np.sinh(y)


def make_combined_interp(slice3d, method: str, domain: str):
    """
    Build a single RegularGridInterpolator that returns all variables at once.
    The variable order follows DATA_KEYS, restricted to those present in the
    slice. Each query call shares the locate/weight computation across all
    output variables, which is the main speed win versus per-variable interp.
    """
    axes = slice3d["axes"]
    grid = (axes["VGS"], axes["VDS"], axes["VSB"])
    var_names = [v for v in DATA_KEYS if v in slice3d["data"]]

    stacked = []
    if domain == "log":
        scales = np.empty(len(var_names), dtype=float)
        for i, v in enumerate(var_names):
            vals = slice3d["data"][v]
            scale = float(np.median(np.abs(vals)))
            if not np.isfinite(scale) or scale == 0:
                scale = 1.0
            scales[i] = scale
            stacked.append(np.arcsinh(vals / scale))
    else:
        scales = None
        for v in var_names:
            stacked.append(slice3d["data"][v])
    values = np.stack(stacked, axis=-1)  # (nVGS, nVDS, nVSB, n_vars)

    rgi = RegularGridInterpolator(
        grid, values, method=method,
        bounds_error=False, fill_value=np.nan,
    )
    return _CombinedInterp(rgi, var_names, scales)


