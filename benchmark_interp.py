def make_query_set(axes_3d, n: int, seed: int = 0):
    """Random uniform query in interior [a+1%span, b-1%span] for each axis."""
    rng = np.random.default_rng(seed)
    out = np.empty((n, 3), dtype=float)
    for i, k in enumerate(("VGS", "VDS", "VSB")):
        a, b = axes_3d[k].min(), axes_3d[k].max()
        margin = 0.01 * (b - a)
        lo, hi = a + margin, b - margin
        if hi <= lo:  # degenerate (e.g. nVSB == 1)
            out[:, i] = a
        else:
            out[:, i] = rng.uniform(lo, hi, size=n)
    assert out.shape == (n, 3)
    return out


# Pinned operating point for single-axis sweeps. These values sit on every
# uniform grid in use (10/25/50/100 mV all divide 0.6 V evenly; 0 V is trivial),
# so the perpendicular axes contribute zero interpolation error and the
# measured error is along the swept axis only.
_AXIS_PIN = {"VGS": 0.6, "VDS": 0.6, "VSB": 0.0}


def make_query_set_axis(axes_3d, n: int, sweep_axis: str, seed: int = 0):
    """
    N random points varying ONLY along `sweep_axis`. The other two axes are
    pinned to grid-aligned values from _AXIS_PIN (clamped to each axis range),
    so the reported error reflects interpolation along `sweep_axis` alone.
    """
    if sweep_axis not in ("VGS", "VDS", "VSB"):
        raise ValueError(f"sweep_axis must be VGS/VDS/VSB, got {sweep_axis!r}")
    rng = np.random.default_rng(seed)
    out = np.empty((n, 3), dtype=float)
    for i, k in enumerate(("VGS", "VDS", "VSB")):
        ax = axes_3d[k]
        if k == sweep_axis:
            a, b = float(ax.min()), float(ax.max())
            margin = 0.01 * (b - a)
            lo, hi = a + margin, b - margin
            if hi <= lo:
                out[:, i] = a
            else:
                out[:, i] = rng.uniform(lo, hi, size=n)
        else:
            pin = float(np.clip(_AXIS_PIN[k], ax.min(), ax.max()))
            out[:, i] = pin
    return out


def time_build(slice3d, var, method, domain):
    t0 = time.perf_counter()
    f = make_interp(slice3d, var, method, domain)
    return time.perf_counter() - t0, f


def time_query(f, query_pts, repeats: int):
    """Returns (median total wall-seconds across repeats, last result vec)."""
    # warmup
    y = f(query_pts)
    times = []
    for _ in range(repeats):
        t0 = time.perf_counter()
        y = f(query_pts)
        times.append(time.perf_counter() - t0)
    return float(np.median(times)), y


