#!/usr/bin/env python3
"""
benchmark_interp.py — Compare interpolation speed and accuracy of LUT tables
generated by run_lut_char_all.py.

Sweeps four axes:
    grid spacing  (25 mV / 50 mV / ... — auto-discovered from filenames)
    method        (linear / pchip)
    domain        (linear / log)
    variable      (ID, GM, GDS, CGG, ... — all 14 by default)

Accuracy is measured against the finest grid available for the chosen
device, evaluated with the SAME (method, domain) so the metric isolates
the grid-spacing contribution.

Usage:
    python benchmark_interp.py
    python benchmark_interp.py --device sg13_lv_pmos --corner SS --temp -40
    python benchmark_interp.py --no-plot --no-accuracy
    python benchmark_interp.py --n-query 20000 --repeats 3
"""

import argparse
import glob
import re
import sys
import time
from pathlib import Path

import numpy as np
import scipy.io
from scipy.interpolate import RegularGridInterpolator

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

DATA_KEYS = [
    "ID", "VT", "GM", "GMB", "GDS",
    "CGG", "CGB", "CGD", "CGS", "CDD", "CSS",
    "STH", "SFL", "VDSAT",
]

METHODS = ["linear", "pchip"]
DOMAINS = ["linear", "log"]

# Per-variable absolute floor for the "true relative error" metric.
# Points where |y_ref| < floor are excluded (signal below this is noise/cutoff
# and meaningless to a designer — including them blows the metric up by
# dividing by ~0). Tune in CLI via --floor VAR=val.
ABS_FLOOR = {
    "ID":    1e-12,   # 1 pA  (below: deep cutoff)
    "VT":    1e-3,    # 1 mV
    "GM":    1e-9,    # 1 nS  (≈ 40·ID at GM/ID=40, so ID floor ≈ 25pA)
    "GMB":   1e-10,
    "GDS":   1e-10,
    "CGG":   1e-18,   # 1 aF
    "CGB":   1e-18,
    "CGD":   1e-18,
    "CGS":   1e-18,
    "CDD":   1e-18,
    "CSS":   1e-18,
    "STH":   1e-25,   # V²/Hz (or A²/Hz) thermal-noise PSD
    "SFL":   1e-25,   # flicker-noise PSD
    "VDSAT": 1e-3,    # 1 mV
}

# Matches uniform-grid files only: {device}_{corner}_T{p|m}{T}_uvgs{X}mV_uvds{Y}mV_vsb{N}.mat
_FILE_RE = re.compile(
    r"^(?P<device>.+?)_(?P<corner>TT|FF|SS|SF|FS)_T(?P<tsign>[pm])(?P<tval>\d+)"
    r"_uvgs(?P<vgs_step>[\d.]+)mV_uvds(?P<vds_step>[\d.]+)mV_vsb(?P<nvsb>\d+)\.mat$"
)

EPS = 1e-30  # log-domain floor


# ---------------------------------------------------------------------------
# Phase 1 — Loader & 3-D slicer
# ---------------------------------------------------------------------------

def parse_filename(name: str):
    """Return dict of file metadata, or None if name doesn't match."""
    m = _FILE_RE.match(name)
    if not m:
        return None
    tsign = m.group("tsign")
    tval = int(m.group("tval"))
    return {
        "device":   m.group("device"),
        "corner":   m.group("corner"),
        "temp":     tval if tsign == "p" else -tval,
        "vgs_step": float(m.group("vgs_step")) / 1000.0,  # mV → V
        "vds_step": float(m.group("vds_step")) / 1000.0,
        "n_vsb":    int(m.group("nvsb")),
    }


def discover_files(input_dir: Path, device: str, corner: str, temp: int):
    """
    Find all uniform-grid .mat files matching (device, corner, temp).
    Returns list of dicts sorted by vgs_step ascending (finest first).
    """
    results = []
    for path in sorted(input_dir.glob("*.mat")):
        meta = parse_filename(path.name)
        if meta is None:
            continue
        if meta["device"] != device:    continue
        if meta["corner"] != corner:    continue
        if meta["temp"]   != temp:      continue
        meta["path"] = path
        results.append(meta)
    results.sort(key=lambda d: d["vgs_step"])
    return results


def load_mat_table(path: Path):
    """
    Load a .mat file produced by run_lut_char_all.py and return:
        {
          "axes": {"L":..., "VGS":..., "VDS":..., "VSB":...},
          "data": {var: ndarray of shape (nL, nVGS, nVDS, nVSB)},
          "meta": filename metadata + W, NFING, INFO
        }
    """
    raw = scipy.io.loadmat(str(path), simplify_cells=True)
    keys = [k for k in raw if not k.startswith("_")]
    if len(keys) != 1:
        raise ValueError(f"{path}: expected 1 top-level key, found {keys}")
    d = raw[keys[0]]

    axes = {
        "L":   np.atleast_1d(np.array(d["L"],   dtype=float)),
        "VGS": np.atleast_1d(np.array(d["VGS"], dtype=float)),
        "VDS": np.atleast_1d(np.array(d["VDS"], dtype=float)),
        "VSB": np.atleast_1d(np.array(d["VSB"], dtype=float)),
    }
    expected_shape = tuple(len(axes[k]) for k in ("L", "VGS", "VDS", "VSB"))

    data = {}
    for k in DATA_KEYS:
        if k not in d:
            continue
        arr = np.array(d[k], dtype=float)
        if arr.shape != expected_shape:
            raise ValueError(
                f"{path}: var {k} shape {arr.shape} != axes {expected_shape}"
            )
        data[k] = arr

    fname_meta = parse_filename(path.name) or {}
    fname_meta.update({
        "info":  d.get("INFO", ""),
        "W":     float(np.array(d.get("W",     np.nan)).flat[0]),
        "NFING": float(np.array(d.get("NFING", np.nan)).flat[0]),
    })

    return {"axes": axes, "data": data, "meta": fname_meta}


def slice_3d(table, L_index: int):
    """Return {axes: {VGS, VDS, VSB}, data: {var: 3-D array at L_index}}."""
    axes_3d = {k: table["axes"][k] for k in ("VGS", "VDS", "VSB")}
    data_3d = {k: v[L_index] for k, v in table["data"].items()}
    return {"axes": axes_3d, "data": data_3d, "meta": table["meta"]}


def validate_axes(table_ref, table_test):
    """Assert ref & test tables share L/VSB axes and VGS/VDS bounds."""
    for k in ("L", "VSB"):
        a, b = table_ref["axes"][k], table_test["axes"][k]
        if a.shape != b.shape or not np.allclose(a, b, atol=1e-9):
            raise AssertionError(
                f"axis {k} differs between ref {table_ref['meta']['vgs_step']*1000:g}mV "
                f"and test {table_test['meta']['vgs_step']*1000:g}mV"
            )
    for k in ("VGS", "VDS"):
        a, b = table_ref["axes"][k], table_test["axes"][k]
        if not (np.isclose(a[0], b[0]) and np.isclose(a[-1], b[-1])):
            raise AssertionError(
                f"axis {k} bounds differ: ref [{a[0]:g},{a[-1]:g}] "
                f"vs test [{b[0]:g},{b[-1]:g}]"
            )


