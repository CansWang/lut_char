def print_table(rows):
    cols = ["axis", "var", "grid(mV)", "method", "domain",
            "build_ms", "qps",
            "rms_err", "p99_err", "max_err",
            "rms_rel", "max_rel", "kept"]
    widths = [max(len(c), max(len(str(r[c])) for r in rows)) for c in cols]
    sep = "|".join("-" * (w + 2) for w in widths)
    hdr = "|".join(f" {c.ljust(w)} " for c, w in zip(cols, widths))
    print(hdr)
    print(sep)
    for r in rows:
        line = "|".join(f" {str(r[c]).ljust(w)} " for c, w in zip(cols, widths))
        print(line)


def _grid_styles(grids):
    """
    Map each grid label to a (size, lightness, edge_w, alpha) style for
    visually distinct grids. Grids in ascending order (finest first):
        finest   → small, light tint, thin edge
        coarsest → large, dark shade, thick edge
    Faces use alpha < 1 so overlapping markers don't fully eclipse each other.
    """
    n = len(grids)
    out = {}
    for i, g in enumerate(grids):
        t = i / max(1, n - 1)  # 0 → 1
        out[g] = {
            "size":      6.0 + 5.0 * t,    # 6 → 11
            "lightness": 1.6 - 1.05 * t,    # 1.6 (light) → 0.55 (dark)
            "edge_w":    1.0 + 1.0 * t,     # 1.0 → 2.0
            "alpha":     0.75,
        }
    return out


def _adjust_lightness(rgb, factor: float):
    """Lighten (>1) or darken (<1) an RGB color via HLS lightness scaling."""
    import colorsys
    r, g, b = rgb[:3]
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    return colorsys.hls_to_rgb(h, max(0.0, min(1.0, l * factor)), s)


def make_plot(rows, out_path: Path, metric_key: str, y_label: str,
              title_suffix: str = ""):
    import matplotlib.pyplot as plt
    import matplotlib.colors as mcolors
    import matplotlib.lines as mlines
    method_color = {"linear": "C0", "pchip": "C3"}
    domain_marker = {"linear": "o", "log": "s"}
    grids = sorted({r["grid(mV)"] for r in rows}, key=float)
    styles = _grid_styles(grids)

    vars_present = [v for v in DATA_KEYS if any(r["var"] == v for r in rows)]
    n = len(vars_present)
    cols = 4
    nrows = int(np.ceil(n / cols))
    fig, axes = plt.subplots(nrows, cols, figsize=(cols * 3.5, nrows * 2.8),
                             squeeze=False)
    for ax in axes.flat[n:]:
        ax.axis("off")

    # Draw coarsest grid first so the smallest markers end up on top of the
    # z-stack instead of being eclipsed by the larger ones.
    rows_zsorted = sorted(rows, key=lambda r: -float(r["grid(mV)"]))
    for ax, var in zip(axes.flat, vars_present):
        plotted_any = False
        for r in rows_zsorted:
            if r["var"] != var:
                continue
            qps = r["_qps"]
            err = r[metric_key]
            if not np.isfinite(qps):
                continue
            if not (np.isfinite(err) and err > 0):
                continue  # skip ref rows / non-comparable entries
            color = method_color[r["method"]]
            style = styles[r["grid(mV)"]]
            base_rgb = mcolors.to_rgb(color)
            face_rgb = _adjust_lightness(base_rgb, style["lightness"])
            face_rgba = (*face_rgb, style["alpha"])
            ax.loglog(
                [qps], [err],
                marker=domain_marker[r["domain"]],
                markeredgecolor=base_rgb,
                markerfacecolor=face_rgba,
                markersize=style["size"],
                markeredgewidth=style["edge_w"],
                linestyle="none",
            )
            plotted_any = True
        ax.set_title(var, fontsize=7)
        ax.set_xlabel("queries / sec", fontsize=6)
        ax.set_ylabel(y_label, fontsize=6)
        # which='both' so MINOR tick labels (e.g. "5×10⁵" between 10⁵ and 10⁶
        # on a narrow log range) match the major-tick label size. Without
        # this, minor labels keep their default ~10pt and look bigger than
        # the major "10⁵"/"10⁶" labels.
        ax.tick_params(labelsize=5, which='both')
        ax.grid(True, which="both", linewidth=0.3, alpha=0.5)
        if plotted_any:
            ax.set_yscale("log")

    handles = []
    labels = []
    for m in METHODS:
        for d in DOMAINS:
            handles.append(mlines.Line2D(
                [], [], marker=domain_marker[d], color=method_color[m],
                markersize=8, linestyle="none", label=f"{m} / {d}"
            ))
            labels.append(f"{m} / {d}")
    for g in grids:
        style = styles[g]
        face = _adjust_lightness((0.35, 0.35, 0.35), style["lightness"])
        handles.append(mlines.Line2D(
            [], [], marker="o",
            markeredgecolor="0.15",
            markerfacecolor=face,
            markersize=style["size"],
            markeredgewidth=style["edge_w"],
            linestyle="none",
            label=f"grid {g} mV",
        ))
        labels.append(f"grid {g} mV")

    fig.legend(handles, labels, loc="lower center", ncol=4, fontsize=8,
               bbox_to_anchor=(0.5, -0.01))
    fig.suptitle(f"LUT interpolation speed vs accuracy ({y_label}){title_suffix}",
                 fontsize=12)
    fig.tight_layout(rect=(0, 0.04, 1, 0.96))
    fig.savefig(out_path, dpi=200, bbox_inches="tight")
    print(f"Plot saved to {out_path}")


