# Phase 4 — Accuracy vs reference (finest grid)
# ---------------------------------------------------------------------------

def relative_error(y_test, y_ref):
    """RMS, p99, and max of |(y_test - y_ref) / (|y_ref| + scale)| ignoring NaN."""
    mask = np.isfinite(y_test) & np.isfinite(y_ref)
    if not mask.any():
        return np.nan, np.nan, np.nan
    yt, yr = y_test[mask], y_ref[mask]
    scale = np.median(np.abs(yr))
    if scale == 0 or not np.isfinite(scale):
        scale = 1.0
    rel = np.abs((yt - yr) / (np.abs(yr) + scale))
    return (float(np.sqrt(np.mean(rel ** 2))),
            float(np.quantile(rel, 0.99)),
            float(np.max(rel)))


def relative_error_true(y_test, y_ref, floor: float):
    """
    Pure relative error |y_test - y_ref| / |y_ref|, restricted to points
    where |y_ref| >= floor. Returns (rms, p99, max, n_kept, n_total).
    Excluding sub-floor points avoids dividing by ~0 in cutoff/deep-subthreshold
    regions where the signal is physically meaningless.
    """
    finite = np.isfinite(y_test) & np.isfinite(y_ref)
    mask = finite & (np.abs(y_ref) >= floor)
    n_total = int(finite.sum())
    n_kept = int(mask.sum())
    if n_kept == 0:
        return np.nan, np.nan, np.nan, 0, n_total
    yt, yr = y_test[mask], y_ref[mask]
    rel = np.abs((yt - yr) / yr)
    return (float(np.sqrt(np.mean(rel ** 2))),
            float(np.quantile(rel, 0.99)),
            float(np.max(rel)),
            n_kept, n_total)


